import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Generates a compact, paste-ready SQL script from a migration file.
 *
 * Why: the Supabase SQL Editor is where migrations are applied by hand, and
 * the reviewed migration files are long and heavily commented. This produces a
 * short, ASCII-only script that is *provably identical* to the reviewed file
 * (comments and whitespace normalised away), so there is no drift between
 * what is reviewed in the repository and what is executed.
 *
 * Usage: node scripts/generate-paste-script.mjs supabase/migrations/0019_operational_schema.sql
 */

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const input = process.argv[2] ?? "supabase/migrations/0019_operational_schema.sql";
const out = process.argv[3] ?? input.replace(/\.sql$/, ".paste.sql");

const ascii = (s) =>
  s
    .replace(/[·]/g, "-")
    .replace(/[—–]/g, "-")
    .replace(/[₦]/g, "NGN ")
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[^\x00-\x7F]/g, "");

/** Removes a trailing `--` comment, ignoring `--` inside string literals. */
const stripInlineComment = (line) => {
  let inStr = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === "'") inStr = !inStr;
    if (inStr) continue;
    if (ch === "-" && line[i + 1] === "-") return line.slice(0, i).trimEnd();
  }
  return line.trimEnd();
};

const src = fs.readFileSync(path.join(root, input), "utf8");
const statements = [];
let buf = [];
let depth = 0;

for (const raw of ascii(src).split(/\r?\n/)) {
  const line = stripInlineComment(raw);
  const trimmed = line.trim();
  if (!trimmed) continue;
  buf.push(trimmed);
  depth += (line.match(/\(/g) || []).length - (line.match(/\)/g) || []).length;
  if (depth <= 0) {
    statements.push(buf.join(" ").replace(/\s+/g, " ").trim());
    buf = [];
    depth = 0;
  }
}
if (buf.length) statements.push(buf.join(" ").replace(/\s+/g, " ").trim());

const header = [
  "-- ============================================================",
  `-- ${path.basename(input)} (paste version, generated by`,
  "-- scripts/generate-paste-script.mjs — do not edit by hand)",
  "-- Safe to re-run: 'if not exists' / 'on conflict do nothing'.",
  "-- ============================================================",
];

const script = header.concat(statements).join("\n") + "\n";
fs.writeFileSync(path.join(root, out), script, "utf8");
console.log(`generated ${out}: ${statements.length} statements, ${script.split("\n").length} lines`);
